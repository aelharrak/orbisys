/// Table `texte français → traduction` d'une langue à fichier (`src/lang/ui_<code>.tsv`).
fn file_table(lang: Lang) -> Option<&'static std::collections::HashMap<&'static str, &'static str>> {
    use std::collections::HashMap;
    use std::sync::OnceLock;
    static TABLES: OnceLock<HashMap<Lang, HashMap<&'static str, &'static str>>> = OnceLock::new();
    let tables = TABLES.get_or_init(|| {
        let sources: [(Lang, &'static str); 8] = [
            (Lang::De, include_str!("lang/ui_de.tsv")),
            (Lang::Pt, include_str!("lang/ui_pt.tsv")),
            (Lang::It, include_str!("lang/ui_it.tsv")),
            (Lang::Nl, include_str!("lang/ui_nl.tsv")),
            (Lang::Ja, include_str!("lang/ui_ja.tsv")),
            (Lang::Ko, include_str!("lang/ui_ko.tsv")),
            (Lang::Zh, include_str!("lang/ui_zh.tsv")),
            (Lang::Ar, include_str!("lang/ui_ar.tsv")),
        ];
        sources
            .into_iter()
            .map(|(lang, text)| (lang, crate::i18n::parse_tsv(lang, text)))
            .collect()
    });
    tables.get(&lang)
}

/// Traduit un libellé statique ; renvoie le texte d'origine s'il est inconnu.
/// Langues à fichier : leur table, puis l'anglais.
pub fn tr(lang: Lang, text: &str) -> String {
    if lang == Lang::Fr {
        return text.to_string();
    }
    if let Some(found) = file_table(lang).and_then(|table| table.get(text)) {
        return (*found).to_string();
    }
    match TABLE.iter().find(|(fr, _, _)| *fr == text) {
        // Sans traduction propre : espagnol pour l'espagnol, anglais pour les autres.
        Some((_, en, es)) => (if lang == Lang::Es { *es } else { *en }).to_string(),
        None => text.to_string(),
    }
}

/// Langue courante des écrans dédiés (index dans `Lang::ALL`) ; partagée avec les
/// threads de lecture, qui produisent eux aussi des messages.
static CURRENT: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(1);

/// Fixe la langue des textes passés par `ts` et `fill`.
pub fn set_lang(lang: Lang) {
    let index = Lang::ALL.iter().position(|candidate| *candidate == lang).unwrap_or(1);
    CURRENT.store(index, std::sync::atomic::Ordering::Relaxed);
}

fn current() -> Lang {
    Lang::ALL[CURRENT.load(std::sync::atomic::Ordering::Relaxed).min(Lang::ALL.len() - 1)]
}

/// Traduction statique d'un libellé : même règle que `tr`, sans allocation.
fn lookup(lang: Lang, text: &'static str) -> &'static str {
    if lang == Lang::Fr {
        return text;
    }
    if let Some(table) = file_table(lang) {
        // Les fichiers écrivent les sauts de ligne `\n` ; la clé est reconstituée.
        let found = if text.contains('\n') { table.get(text.replace('\n', "\\n").as_str()) } else { table.get(text) };
        if let Some(found) = found {
            return found;
        }
    }
    match TABLE.iter().find(|(fr, _, _)| *fr == text) {
        Some((_, en, es)) => {
            if lang == Lang::Es {
                es
            } else {
                en
            }
        }
        None => text,
    }
}

/// La langue courante est-elle le français (langue source des textes) ?
pub fn is_french() -> bool {
    current() == Lang::Fr
}

/// Traduit un texte produit à l'exécution : correspondance exacte, puis gabarit à `{}`
/// (« 3 noyau(x) plus ancien(s)… »). Un texte inconnu est rendu tel quel. Les résultats
/// sont mémorisés : l'affichage rappelle cette fonction à chaque image.
pub fn tx(text: &str) -> String {
    use std::collections::HashMap;
    use std::sync::{Mutex, OnceLock};
    let lang = current();
    if lang == Lang::Fr || text.is_empty() {
        return text.to_string();
    }
    static CACHE: OnceLock<Mutex<HashMap<(Lang, String), String>>> = OnceLock::new();
    let cache = CACHE.get_or_init(|| Mutex::new(HashMap::new()));
    if let Some(found) = cache.lock().ok().and_then(|map| map.get(&(lang, text.to_string())).cloned()) {
        return found;
    }
    let exact = tr(lang, text);
    let result = if exact != text {
        exact
    } else {
        TABLE
            .iter()
            .filter(|(fr, _, _)| fr.contains("{}"))
            .find_map(|(fr, _, _)| match_template(fr, text).map(|values| (*fr, values)))
            .map(|(template, values)| {
                let values: Vec<String> = values.iter().map(|value| tr(lang, value)).collect();
                let refs: Vec<&dyn std::fmt::Display> = values.iter().map(|value| value as &dyn std::fmt::Display).collect();
                lookup_fill(lang, template, &refs)
            })
            .unwrap_or_else(|| text.to_string())
    };
    if let Ok(mut map) = cache.lock() {
        if map.len() > 4096 {
            map.clear();
        }
        map.insert((lang, text.to_string()), result.clone());
    }
    result
}

/// Valeurs de `text` si elle suit le gabarit français `template` (`{}` = un morceau quelconque).
fn match_template(template: &str, text: &str) -> Option<Vec<String>> {
    let parts: Vec<&str> = template.split("{}").collect();
    if parts.iter().map(|part| part.len()).sum::<usize>() < 4 {
        return None;
    }
    let first = parts[0];
    let last = parts[parts.len() - 1];
    let mut rest = text.strip_prefix(first)?;
    let mut values = Vec::new();
    for part in &parts[1..parts.len() - 1] {
        let at = rest.find(part)?;
        values.push(rest[..at].to_string());
        rest = &rest[at + part.len()..];
    }
    let body = rest.strip_suffix(last)?;
    values.push(body.to_string());
    Some(values)
}

/// Libellé d'écran dédié dans la langue courante (le texte d'origine s'il est inconnu).
pub fn ts(text: &'static str) -> &'static str {
    lookup(current(), text)
}

/// Gabarit traduit (`{}` ou `{1}`, `{2}`… pour réordonner) rempli avec ses valeurs.
pub fn fill(template: &'static str, args: &[&dyn std::fmt::Display]) -> String {
    lookup_fill(current(), template, args)
}

fn lookup_fill(lang: Lang, template: &'static str, args: &[&dyn std::fmt::Display]) -> String {
    let text = lookup(lang, template);
    let mut out = String::with_capacity(text.len() + 16);
    let mut next = 0;
    let mut rest = text;
    while let Some(start) = rest.find('{') {
        out.push_str(&rest[..start]);
        let Some(end) = rest[start..].find('}') else {
            rest = &rest[start..];
            break;
        };
        let name = &rest[start + 1..start + end];
        let index = match name.parse::<usize>() {
            Ok(number) if number >= 1 => number - 1,
            _ => {
                next += 1;
                next - 1
            }
        };
        match args.get(index) {
            Some(value) if name.is_empty() || name.parse::<usize>().is_ok() => out.push_str(&value.to_string()),
            _ => out.push_str(&rest[start..start + end + 1]),
        }
        rest = &rest[start + end + 1..];
    }
    out.push_str(rest);
    out
}

/// Clés françaises d'une langue à fichier (tests).
pub fn file_keys(lang: Lang) -> Vec<&'static str> {
    file_table(lang).map(|table| table.keys().copied().collect()).unwrap_or_default()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn translates_known_labels_and_keeps_unknown_ones() {
        assert_eq!(tr(Lang::En, "Fichier"), "File");
        assert_eq!(tr(Lang::Es, "Fichier"), "Archivo");
        assert_eq!(tr(Lang::Fr, "Fichier"), "Fichier");
        assert_eq!(tr(Lang::En, "texte inconnu 42"), "texte inconnu 42");
    }

    #[test]
    fn file_languages_cover_every_label() {
        for lang in Lang::ALL {
            let keys: std::collections::HashSet<&str> = file_keys(lang).into_iter().collect();
            if keys.is_empty() {
                continue;
            }
            for (fr, _, _) in TABLE.iter() {
                assert!(keys.contains(fr.replace('\n', "\\n").as_str()), "{} : libellé non traduit « {fr} »", lang.code());
            }
            for key in &keys {
                assert!(TABLE.iter().any(|(fr, _, _)| fr.replace('\n', "\\n") == *key), "{} : libellé inconnu « {key} »", lang.code());
            }
        }
    }

    #[test]
    fn file_languages_translate_labels_and_fall_back_to_english() {
        assert_eq!(tr(Lang::De, "Fichier"), "Datei");
        assert_eq!(tr(Lang::Ja, "Fichier"), "ファイル");
        assert_eq!(tr(Lang::De, "Lecture seule : aucune donnée du système n'est modifiée."), "Nur lesend: Am System wird nichts geändert.");
        assert_eq!(tr(Lang::De, "texte inconnu 42"), "texte inconnu 42");
        // L'arabe est mis en forme visuelle au chargement.
        assert!(tr(Lang::Ar, "Fichier").chars().any(|ch| ('\u{FE70}'..='\u{FEFF}').contains(&ch)));
    }

    #[test]
    fn fill_substitutes_in_order_or_by_number() {
        let args: [&dyn std::fmt::Display; 2] = [&3, &"x"];
        assert_eq!(fill("{} sur {}", &args), "3 sur x");
        assert_eq!(fill("sans valeur", &args), "sans valeur");
    }

    #[test]
    fn every_dedicated_screen_label_is_in_the_table() {
        let source = include_str!("gui.rs");
        for marker in ["ts(\"", "tf(\""] {
            for (at, _) in source.match_indices(marker) {
                let before = source[..at].chars().last().unwrap_or(' ');
                if before.is_alphanumeric() || before == '_' {
                    continue;
                }
                let rest = &source[at + marker.len()..];
                let mut end = 0;
                let bytes = rest.as_bytes();
                while bytes[end] != b'"' {
                    end += if bytes[end] == b'\\' { 2 } else { 1 };
                }
                let label = rest[..end].replace("\\n", "\n").replace("\\\"", "\"");
                assert!(TABLE.iter().any(|(fr, _, _)| *fr == label), "libellé de gui.rs absent de la table : « {label} »");
            }
        }
    }

    #[test]
    fn table_has_no_duplicates_or_empty_entries() {
        let mut seen = std::collections::HashSet::new();
        for (fr, en, es) in TABLE {
            assert!(seen.insert(*fr), "doublon : {fr}");
            assert!(!fr.is_empty() && !en.is_empty() && !es.is_empty(), "entrée vide : {fr}");
        }
    }
}
