#!/usr/bin/env bash
# Construit un paquet Arch Linux (.pkg.tar.zst) à partir du binaire déjà compilé.
#
#   cd rust/orbisys
#   cargo build --release
#   ./packaging/build-arch.sh           # produit dist/orbisys-<version>-<rel>-<arch>.pkg.tar.zst
#
# Ce paquet ne remplace pas le PKGBUILD (qui recompile depuis les sources) : il
# sert à tester l'installation sur Arch sans chaîne de compilation.
# Dépendances : tar et zstd. Aucun privilège requis.

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CRATE="$(cd "$HERE/.." && pwd)"
BIN="${ORBISYS_BIN:-$CRATE/target/release/orbisys}"
VERSION="$(sed -n 's/^version *= *"\(.*\)"/\1/p' "$CRATE/Cargo.toml" | head -1)"
PKGREL=1
ARCH="$(uname -m)"
DIST="$CRATE/dist"
OUT="$DIST/orbisys-${VERSION}-${PKGREL}-${ARCH}.pkg.tar.zst"

[ -x "$BIN" ] || { echo "Binaire absent : lancer 'cargo build --release' d'abord." >&2; exit 1; }
command -v zstd >/dev/null || { echo "zstd est requis." >&2; exit 1; }
mkdir -p "$DIST"

STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
install -Dm0755 "$BIN" "$STAGE/usr/bin/orbisys"
install -Dm0644 "$HERE/orbisys.desktop" "$STAGE/usr/share/applications/orbisys.desktop"
install -Dm0644 "$HERE/orbisys.svg" "$STAGE/usr/share/icons/hicolor/scalable/apps/orbisys.svg"
SIZE="$(du -sb "$STAGE/usr" | cut -f1)"

cat > "$STAGE/.PKGINFO" <<EOF
# Generated by OrbiSys build-arch.sh
pkgname = orbisys
pkgbase = orbisys
pkgver = ${VERSION}-${PKGREL}
pkgdesc = Gestionnaire de système : paquets, disques, réseau, sécurité
url = https://github.com/aelharrak/orbisys
builddate = $(date +%s)
packager = OrbiSys <noreply@example.com>
size = $SIZE
arch = $ARCH
license = MIT
depend = glibc
depend = gcc-libs
depend = polkit
EOF

( cd "$STAGE" && tar --format=posix --owner=0 --group=0 --numeric-owner -cf - .PKGINFO usr \
  | zstd -q -19 -T0 -f -o "$OUT" )
echo "Paquet créé : $OUT"
